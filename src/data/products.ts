/**
 * src/data/products.ts
 *
 * Typed product catalogue for Elit Dekor.
 * Download formats: 3ds, max, obj, pdf (4 formats only).
 * Image URLs are public-root-relative ("/products/...").
 */

// ─── Types ───────────────────────────────────────────────────────────────────

export type Availability = 'in_stock' | 'made_to_order';

export type Category =
  | 'karnizy'
  | 'rozetki'
  | 'moldinghi'
  | 'friezes'
  | 'columns'
  | 'panels'
  | 'other';

export interface ProductImages {
  card: string;
  main: string;
  thumb: string;
  og: string;
  interior?: string;
  profile?: string;
  gallery?: string[];
}

export interface ProductDownloads {
  '3ds'?: string;
  max?: string;
  obj?: string;
  pdf?: string;
}

export interface Product {
  slug: string;
  code: string;
  category: Category;
  name: string;
  material: string;
  heightMm: number;
  depthMm: number;
  weightKgPerM: number;
  pricePerMeter: number;
  pieceLengthM: number;
  minOrderM: number;
  availability: Availability;
  shortDescription: string;
  description: string;
  images: ProductImages;
  model3d?: string;
  downloads?: ProductDownloads;
}

// ─── Currency / unit config ──────────────────────────────────────────────────

export const CURRENCY_LABEL = "so'm";
export const UNIT_LABEL = 'p.m.';

export function formatPrice(pricePerMeter: number): string {
  return `${pricePerMeter.toLocaleString('uz-UZ')} ${CURRENCY_LABEL}/${UNIT_LABEL}`;
}

export function formatDimensions(heightMm: number, depthMm: number): string {
  return `${heightMm}×${depthMm} mm`;
}

// ─── Helper to build standard image paths ────────────────────────────────────

function imgs(slug: string): ProductImages {
  return {
    card: `/products/${slug}/card.webp`,
    main: `/products/${slug}/main.webp`,
    thumb: `/products/${slug}/thumb.webp`,
    og: `/products/${slug}/og.jpg`,
  };
}

function dl(slug: string): ProductDownloads {
  return {
    '3ds': `/products/${slug}/downloads/${slug}.3ds`,
    max: `/products/${slug}/downloads/${slug}.max`,
    obj: `/products/${slug}/downloads/${slug}.obj`,
    pdf: `/products/${slug}/downloads/${slug}.pdf`,
  };
}

